#!/usr/bin/env node
'use strict';
/*
 * RENDER THE LEDGER AS A HUMAN VIEW.
 *
 *   node tools/learnloop/bin/render-status.js [--out PROMOTION-STATUS.md] [--check]
 *
 * The JSON is the artifact; this is a rendering of it and is regenerated, never
 * edited. `--check` re-renders and exits nonzero if the committed file has
 * drifted from the ledger — so a ledger change that forgot to re-render is a
 * failing gate rather than a stale document nobody trusts.
 */

const fs = require('fs');
const path = require('path');
const L = require('../lib/ledger');

function arg(name, dflt) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && i + 1 < process.argv.length ? process.argv[i + 1] : dflt;
}
const CHECK = process.argv.includes('--check');
const outFile = path.resolve(arg('out', path.join(__dirname, '..', 'PROMOTION-STATUS.md')));
const ledger = L.load(arg('ledger', L.LEDGER_PATH));

const BADGE = {
  dark: 'dark',
  'probe-passed': 'probe only',
  'live-null': 'live null',
  'live-failed': 'LIVE FAILED',
  supported: 'supported — flip owed',
  promoted: 'PROMOTED',
  frozen: 'frozen',
};

const out = [];
const w = (s = '') => out.push(s);

w('# Promotion status');
w();
w('**Generated from `tools/learnloop/promotion-ledger.json` by');
w('`bin/render-status.js`. Do not edit this file — edit the ledger and re-render.**');
w();
w(`Seeded ${ledger.seededAt} by ${ledger.seededBy}. ${ledger.flags.length} flags tracked.`);
w();
w('## The rule this table exists to enforce');
w();
for (const line of ledger.readMe.slice(4)) w(line);
w();
w('## Where every flag stands');
w();
w('| flag | stage | status | default | next experiment |');
w('|---|---|---|---|---|');
for (const f of ledger.flags) {
  const nx = f.nextExperiment;
  w(
    `| \`${f.flag}\` | ${f.stage} | **${BADGE[f.status]}** | \`${f.shipsDefault}\` | ` +
      `${nx ? `${nx.id}${nx.withdrawn ? ' *(WITHDRAWN)*' : nx.blockedOn ? ' *(blocked)*' : ''}` : '—'} |`
  );
}
w();

const counts = {};
for (const f of ledger.flags) counts[f.status] = (counts[f.status] ?? 0) + 1;
w(
  'Counts: ' +
    Object.entries(counts)
      .map(([k, v]) => `${v} ${BADGE[k]}`)
      .join(', ') +
    '.'
);
w();

w('## What each flag owes, and what it has');
w();
for (const f of ledger.flags) {
  w(`### \`${f.flag}\` — ${BADGE[f.status]}`);
  w();
  w(`*${f.stage}. ${f.whatItDoes}*`);
  w();
  if (f.perEngineOption) w(`- Per engine: \`${f.perEngineOption}\``);
  // HOW AN ARM IS SELECTED TODAY. Rendered because a reader who cannot see it
  // will reach for the flag name in the heading, and the flag name is history:
  // every row here keeps it as its identity, and `selection` is the only field
  // that says what actually asks for the thing now.
  if (f.selection) w(`- **Selected by:** ${f.selection}`);
  if (f.parses) w(`- Parses: ${f.parses}`);
  if (f.requires) w(`- Requires: ${f.requires}`);
  if (f.branch) w(`- Branch: ${f.branch}`);
  if (f.promotedBy) w(`- Promoted by: ${f.promotedBy}`);
  if (f.actionOwed) w(`- **Action owed:** ${f.actionOwed}`);
  w();
  w('**Promotion metrics** (the gate, and whether the build emits it):');
  w();
  w('| metric | family | emitted | source |');
  w('|---|---|---|---|');
  for (const g of f.promotionMetrics ?? []) {
    w(
      `| \`${g.name}\` | ${g.family} | ${g.emitted ? (g.since ? `yes (${g.since})` : 'yes') : '**NO**'} | ` +
        `${g.source}${g.gap ? ` — **gap:** ${g.gap}` : ''}${g.note ? ` ${g.note}` : ''} |`
    );
  }
  w();
  w('**Measurements:**');
  w();
  for (const m of f.measurements ?? []) {
    const tags = [
      m.kind === 'control' ? '**CONTROL CELL**' : m.kind,
      m.nullVerified ? 'null verified' : 'no null',
      // The tri-state, rendered as three things. `false` is a counter that was
      // read and was zero; `null` is cannot say; absent is a row that never
      // addressed it. All three refuse, and a reader should be able to see
      // which one they are looking at.
      m.kind !== 'live'
        ? null
        : m.armEngagementVerified === false
          ? '**ENGAGEMENT SHOWN ZERO**'
          : m.armEngagementVerified === true
            ? 'engagement shown'
            : '**ENGAGEMENT NOT SHOWN** (cannot say)',
      m.polarity && m.polarity !== 'higher-is-better' ? m.polarity : null,
      m.power && m.power.underpowered ? `underpowered (${m.power.blocksHad}/${m.power.blocksNeeded} blocks)` : null,
    ].filter(Boolean);
    w(`- **${m.batch}** · ${m.cell} · \`${m.metric}\` → **${m.verdict}**  `);
    w(`  ${m.value}  `);
    w(`  <sub>${tags.join(' · ')}</sub>`);
    if (m.caveat) w(`  > ${m.caveat}`);
    if (m.note) w(`  > ${m.note}`);
    // THE MACHINE'S OWN RECOMPUTATION OF A ROW SOMEBODY TRANSCRIBED. A row that
    // agrees with the rows it came from and a row nobody has ever checked look
    // identical without this line, and they are not the same row.
    if (m.machineIngest) {
      const mi = m.machineIngest;
      w(`  > *Machine ingest:* ${mi.agreement ? `**${mi.agreement}** — ` : ''}${mi.what ?? mi.why ?? mi.status}`);
      for (const c of mi.perCell ?? []) {
        w(
          `  >   - \`${c.cell}\` (${c.arm}): ${c.mean >= 0 ? '+' : ''}${c.mean} [${c.lo}, ${c.hi}] over ` +
            `${c.blocks} blocks; floor ${c.nullHalfWidth === null ? '**none — UNREADABLE**' : `+/-${c.nullHalfWidth}`}` +
            `${c.outsideNull === true ? ' — **outside the floor**' : ''}`
        );
      }
    }
  }
  w();
  if (f.controlEvidence) {
    const ce = f.controlEvidence;
    w('**Control cells** — cells the design requires to read zero. They vouch for the');
    w('instrument and move no status in either direction.');
    w();
    for (const c of ce.inert ?? []) w(`- PASSED (inert as designed): \`${c}\``);
    for (const c of ce.violated ?? []) w(`- **VIOLATED — instrument failure:** \`${c}\``);
    w();
  }
  if (f.manifestMining) {
    const mm = f.manifestMining;
    w(`**Mined from the per-game manifests — ${mm.label}**`);
    w();
    for (const x of mm.findings ?? []) w(`- **${x.id}.** ${x.detail}`);
    w();
    if (mm.whatTheRowsCarry) w(`*What the rows carry:* ${mm.whatTheRowsCarry}`);
    if (mm.stillNeedsReplays) w(`*Still needs turn-level replays:* ${mm.stillNeedsReplays}`);
    w();
  }
  if (f.verdict) {
    w(`**Verdict.** ${f.verdict}`);
    w();
  }
  // A frozen flag's reopen condition is part of its verdict, not a footnote:
  // the schema refuses `frozen` without one precisely so a reader can see what
  // it would take, and a human view that dropped it would hide the only route.
  if (f.status === 'frozen' && f.reopenOn) {
    w(`**Re-opened by.** ${f.reopenOn}`);
    w();
  }
  // AN OPEN FINDING AGAINST THIS ROW, QUOTED. It moves no status by
  // construction — that is what makes it a finding and not a measurement — so
  // the human view is the only place a reader meets it, and burying it would
  // make the view agree with itself while disagreeing with the branch.
  if (f.distillerFinding) {
    const d = f.distillerFinding;
    w(`**OPEN FINDING — ${d.recordedBy}**`);
    w();
    w('> ' + String(d.verbatim).split('\n').join('\n> '));
    w();
    if (d.state) w(d.state);
    if (d.owedRegardless) {
      w();
      w(d.owedRegardless);
    }
    w();
  }
  const nx = f.nextExperiment;
  if (nx) {
    w(`**Next: ${nx.id}.** ${nx.question}`);
    w();
    if (nx.withdrawn) {
      w(`- **WITHDRAWN:** ${nx.withdrawn}`);
      w();
    }
    if (nx.arms) w(`- Arms: ${nx.arms.map((a) => `\`${a}\``).join(' · ')}`);
    if (nx.cells) w(`- Cells: ${nx.cells.join(', ')} at ${nx.blocks} blocks`);
    if (nx.readsOut) w(`- Reads out: ${nx.readsOut.map((r) => `\`${r}\``).join(', ')}`);
    if (nx.designNote) w(`- Design: ${nx.designNote}`);
    if (nx.scopeNote) w(`- Scope: ${nx.scopeNote}`);
    if (nx.gate) w(`- **Gate:** ${nx.gate}`);
    if (nx.requires) w(`- Requires: ${nx.requires}`);
    if (nx.blockedOn) w(`- **Blocked on:** ${nx.blockedOn}`);
    if (nx.priority) w(`- Priority: ${nx.priority}`);
    w();
  }
}

if ((ledger.standingExperiments ?? []).length > 0) {
  w('## Standing experiments');
  w();
  w('Owner-approved program questions that are not any one flag\'s promotion.');
  w();
  for (const x of ledger.standingExperiments) {
    w(`### ${x.id} — ${x.title}`);
    w();
    w(`- Approved by: ${x.approvedBy}`);
    w(`- Trigger: ${x.trigger}`);
    w(`- Question: ${x.question}`);
    if (x.budgets) w(`- Rungs: ${x.budgets.join(' / ')} ms, ${x.blocks} blocks each`);
    if (x.designNote) w(`- Design: ${x.designNote}`);
    if (x.caveat) w(`- Caveat: ${x.caveat}`);
    w();
  }
}

// THE BATCHES, AND WHETHER A MACHINE EVER READ THEM. A ledger whose rows were
// transcribed by a human from a summary is a different artifact from one whose
// rows were recomputed from the games, and the difference belongs on the page.
if ((ledger.batches ?? []).length > 0) {
  w('## Batches');
  w();
  for (const bt of ledger.batches) {
    w(`### ${bt.id}`);
    w();
    w(`- Games: ${bt.games}${bt.gamesRecorded && bt.gamesRecorded !== bt.games ? ` (delivery said ${bt.gamesRecorded})` : ''}`);
    w(`- Ingest: **${bt.ingest ? bt.ingest.mode : 'no record'}**`);
    if (bt.ingest && bt.ingest.theHeadline) w(`- ${bt.ingest.theHeadline}`);
    if (bt.integrity) {
      w(`- Integrity: illegal ${bt.integrity.illegal}, errors ${bt.integrity.errors}`);
      if (bt.integrity.correction) w(`  > ${bt.integrity.correction}`);
      for (const r of bt.integrity.rows ?? []) w(`  > - \`${r}\``);
      if (bt.integrity.ruleConsequence) w(`  > ${bt.integrity.ruleConsequence}`);
    }
    if (bt.instrumentEvents) {
      w('- Instrument events:');
      for (const e of bt.instrumentEvents.events ?? []) {
        w(`  - \`${e.kind}\` ${e.cell}${e.arm ? ` [${e.arm}]` : ''}`);
      }
      if (bt.instrumentEvents.capRateAsymmetryFiredOnP5) {
        w(`  > *cap-rate-asymmetry on P5:* ${bt.instrumentEvents.capRateAsymmetryFiredOnP5}`);
      }
      if (bt.instrumentEvents.secondFiring) w(`  > ${bt.instrumentEvents.secondFiring}`);
    }
    if (bt.flipRateProxy) {
      w(`- Paired outcome flip rate (proxy): ${bt.flipRateProxy.reading}`);
    }
    if (bt.ingest && bt.ingest.agreementWithTheHandFold) {
      const a = bt.ingest.agreementWithTheHandFold;
      w(
        `- Machine vs the hand fold: **${a.confirmed} confirmed, ${a.refined} refined, ` +
          `${a.contradicted} contradicted, ${a.notRecomputable} not recomputable.** ${a.note}`
      );
      if (a.refinementsAreOfTwoKinds) w(`  > ${a.refinementsAreOfTwoKinds}`);
    }
    for (const d of (bt.ingest && bt.ingest.stillDeferred) || []) w(`- Still owed: ${d}`);
    w();
  }
}

w('## Open instrument items');
w();
w('Gaps in what can be measured at all. Each names what would close it, and');
w('several are deliberately *not* CL7 items because closing them would change');
w('the decision path.');
w();
for (const i of ledger.openInstrumentItems ?? []) {
  w(`### ${i.id}${i.closedIn ? ' — **CLOSED**' : ''}`);
  w();
  w(i.what);
  w();
  if (i.foundBy) w(`*Found by:* ${i.foundBy}`);
  if (i.exhibit) w(`*Exhibit:* ${i.exhibit}`);
  if (i.impact) w(`*Impact:* ${i.impact}`);
  if (i.consequence) w(`*Consequence:* ${i.consequence}`);
  if (i.workaround) w(`*Workaround:* ${i.workaround}`);
  w(`*Closed by:* ${i.closedBy}`);
  if (i.closedIn) w(`*Closed in:* ${i.closedIn}`);
  w();
}

const text = out.join('\n') + '\n';

if (CHECK) {
  const have = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (have !== text) {
    console.error(`render-status --check: ${path.basename(outFile)} is stale. Re-run without --check.`);
    process.exit(1);
  }
  console.log(`render-status --check: ${path.basename(outFile)} is current.`);
  process.exit(0);
}

fs.writeFileSync(outFile, text);
console.log(`wrote ${outFile} (${out.length} lines)`);
